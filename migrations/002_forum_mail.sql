CREATE TABLE IF NOT EXISTS forum_mail_outbox (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, notification_id INT UNSIGNED NOT NULL UNIQUE,
  state VARCHAR(16) NOT NULL DEFAULT 'pending', attempts INT UNSIGNED NOT NULL DEFAULT 0,
  available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, sent_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(notification_id) REFERENCES forum_notifications(id), INDEX(state,available_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
